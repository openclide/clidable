export function getAgent(id: string): AgentInfo {
  const a = AGENTS.find((x) => x.id === migrateAgentId(id));
  if (a) return a;
  // A stored/wire id we no longer recognize (e.g. a renamed or removed agent)
  // must not crash a render — migrate handles known renames; anything else warns
  // and falls back to the default rather than throwing.
  console.warn(`[agents] unknown agent id "${id}" — falling back to Claude Code`);
  return AGENTS[0]!;
}

/** Compact agent label for tight UI (tab chips, picker grid): drop the
 *  verbose product suffixes so "GitHub Copilot" → "Copilot", etc. */
export function shortAgentName(name: string): string {
  return name.replace(" Code", "").replace(" CLI", "").replace("GitHub ", "");
}

/** "2h ago", "1d ago", "Just now", etc. */
export function relativeTime(ms: number): string {
  const diff = Date.now() - ms;
  const m = Math.floor(diff / 60000);
  if (m < 1) return "just now";
  if (m < 60) return `${m}m ago`;
  const h = Math.floor(m / 60);
  if (h < 24) return `${h}h ago`;
  const d = Math.floor(h / 24);
  if (d < 7) return `${d}d ago`;
  const w = Math.floor(d / 7);
  if (w < 4) return `${w}w ago`;
  return `${Math.floor(d / 30)}mo ago`;
}
